const todasAsImagens = new Map<string, Imagem>(
  [logos.vertical, ...Object.values(imagens).flat(), ...espetaculos.flatMap((e) => e.fotos)].map(
    (img) => [img.src, img],
  ),
);

/** Busca uma imagem por caminho relativo a public/images (ex.: "equipe/02-img-7190.jpg"). */
export function foto(caminho: string, alt?: string): Imagem {
  const img = todasAsImagens.get(`/images/${caminho}`);
  if (!img) throw new Error(`Imagem não encontrada em images.ts: ${caminho}`);
  return alt ? { ...img, alt } : img;
}

/** Primeira foto horizontal do espetáculo (as verticais ficam cortadas em capas largas). */
export function capaDoEspetaculo(espetaculo: Espetaculo): Imagem {
  return espetaculo.fotos.find((f) => f.width / f.height >= 1.3) ?? espetaculo.fotos[0];
}
